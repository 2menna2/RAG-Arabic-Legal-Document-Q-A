"""Render reports/EVALUATION_REPORT.md from the JSON results (no hand-written numbers)."""

from __future__ import annotations

import json
import platform
from importlib import metadata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "reports"


def load(name: str) -> dict:
    p = R / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def fmt(x: object) -> str:
    return f"{x:.3f}" if isinstance(x, float) else str(x)


def main() -> None:
    ev, ret, gates, bench, val = (
        load(n)
        for n in (
            "eval_summary.json",
            "retrieval_eval.json",
            "gates_eval.json",
            "retrieval_benchmark.json",
            "data_quality/validation_report.json",
        )
    )
    llm = load("rag_eval.json")
    cfg = yaml.safe_load((ROOT / "configs/rag.yaml").read_text(encoding="utf-8"))
    libs = {
        p: metadata.version(p)
        for p in ("scikit-learn", "numpy", "rank-bm25", "qdrant-client", "google-genai", "pymupdf", "mlflow", "dvc")
        if _has(p)
    }
    L: list[str] = []
    a = L.append
    a("# Evaluation report")
    a("")
    a("> Generated by `python scripts/render_eval_report.py` from `reports/*.json`. Do not edit numbers by hand.")
    a("")
    a("## Run identity")
    a("")
    a("| item | value |")
    a("|---|---|")
    for k in ("run_at", "git_commit", "dataset", "dataset_hash", "corpus_hash", "index_collection", "rag_config_hash", "environment"):
        a(f"| {k} | `{ev.get(k)}` |")
    emb = ev.get("embedder", {})
    a(f"| embedder | `{emb.get('name')}` / {emb.get('model')} / {emb.get('version')} / dim {emb.get('dim')} |")
    a(
        f"| retrieval | {cfg['retrieval']['method']} {cfg['retrieval']['hybrid_components']} rrf_k={cfg['retrieval']['rrf_k']} top_k={cfg['retrieval']['top_k']} |"
    )
    a(f"| reranker | {'enabled: ' + cfg['reranker']['model'] if cfg['reranker']['enabled'] else 'disabled (not measurable offline)'} |")
    a(f"| LLM | {llm.get('llm_model', 'not evaluated in this run (no GEMINI_API_KEY in the environment)')} |")
    a(f"| python / libraries | {platform.python_version()} / " + ", ".join(f"{k} {v}" for k, v in libs.items()) + " |")
    a("")
    a("## 1. Corpus quality (data validation)")
    a("")
    st = val.get("stats", {})
    a(f"Validation passed: **{val.get('passed')}** — " + ", ".join(f"{k}={v}" for k, v in st.items()))
    a("")
    a("## 2. Retrieval (production configuration, real index)")
    a("")
    a("| split | n | R@1 | R@5 | R@10 | MRR | nDCG@5 | P@5 | Hit@5 |")
    a("|---|---|---|---|---|---|---|---|---|")
    for s in ("dev", "test"):
        m = ret.get("metrics", {}).get(s, {})
        a(
            f"| {s} | {m.get('n')} | "
            + " | ".join(fmt(m.get(k)) for k in ("recall@1", "recall@5", "recall@10", "mrr", "ndcg@5", "precision@5", "hit@5"))
            + " |"
        )
    a("")
    a("By question style (all splits):")
    a("")
    a("| style | n | R@5 | MRR |")
    a("|---|---|---|---|")
    for st_, m in ret.get("by_style", {}).items():
        a(f"| {st_} | {m.get('n')} | {fmt(m.get('recall@5'))} | {fmt(m.get('mrr'))} |")
    a("")
    a("By question type (all splits):")
    a("")
    a("| type | n | R@5 | MRR |")
    a("|---|---|---|---|")
    for t, m in ret.get("by_type", {}).items():
        a(f"| {t} | {m.get('n')} | {fmt(m.get('recall@5'))} | {fmt(m.get('mrr'))} |")
    a("")
    misses = [r for r in ret.get("rows", []) if r["split"] == "test" and r["recall@5"] < 1][:12]
    a("Examples of test-split retrieval misses (expected article not in top-5):")
    a("")
    golden = {i["id"]: i for i in yaml.safe_load((ROOT / "data/evaluation/golden_v1.yaml").read_text(encoding="utf-8"))["items"]}
    for r in misses:
        a(f"- `{r['id']}` ({r['style']}/{r['type']}): expected {r['expected']}, got {r['ranked'][:5]} — {golden[r['id']]['question']}")
    a("")
    a("## 3. Baseline vs improved (retrieval benchmark, same golden questions)")
    a("")
    res = {r["name"]: r for r in bench.get("results", [])}
    pairs = [
        ("reference corpus + dense(LSA)", "reference-reference_article_ar-dense-nodialect"),
        ("reference corpus + hybrid", "reference-reference_article_ar-hybrid[bm25+tfidf+dense]-nodialect"),
        ("new corpus, article chunks + hybrid", "new-article-hybrid[bm25+tfidf+dense]"),
        ("**selected**: new corpus, article_ctx + hybrid", bench.get("selected", "")),
    ]
    a("| configuration | dev R@5 | dev MRR | test R@5 | test MRR | test nDCG@5 |")
    a("|---|---|---|---|---|---|")
    for label, key in pairs:
        if key in res:
            d, t = res[key]["summary"]["dev"], res[key]["summary"]["test"]
            a(f"| {label} | {fmt(d['recall@5'])} | {fmt(d['mrr'])} | {fmt(t['recall@5'])} | {fmt(t['mrr'])} | {fmt(t['ndcg@5'])} |")
    a("")
    a("Full grid (22 configurations, all logged to MLflow): `reports/retrieval_benchmark.md`.")
    a("")
    a("## 4. Decision layer (guardrails → scope → evidence), no LLM")
    a("")
    a(f"Thresholds (calibrated on dev only): `{gates.get('thresholds')}`")
    a("")
    a("| split | n | accuracy | balanced acc. | false-proceed (negatives reaching the LLM) | false-block (answerable stopped) |")
    a("|---|---|---|---|---|---|")
    for s in ("dev", "test"):
        m = gates.get(s, {})
        a(
            f"| {s} | {m.get('n')} | {fmt(m.get('accuracy'))} | {fmt(m.get('balanced_accuracy'))} | {fmt(m.get('false_proceed_rate'))} | {fmt(m.get('false_block_rate'))} |"
        )
    a("")
    for s in ("dev", "test"):
        a(
            f"Per-class accuracy ({s}): `{gates.get(s, {}).get('per_expected_class_accuracy')}` — class sizes `{gates.get(s, {}).get('class_counts')}`"
        )
        a("")
    a("Dev is near-perfect because thresholds and rules were tuned on it; **test is the honest estimate** and shows")
    a("the rule-based gate over-fits: several negatives still reach the LLM, which is the second gate (it may answer")
    a("`out_of_scope`/`insufficient_evidence`), followed by citation validation as the third.")
    a("")
    a("## 5. Generation (LLM) evaluation")
    a("")
    if llm:
        a(f"Model `{llm.get('llm_model')}`, split `{llm.get('split')}`, run {llm.get('run_at')}:")
        a("")
        for k, v in llm.get("metrics", {}).items():
            a(f"- {k}: {fmt(v)}")
    else:
        a("**Not executed.** The execution environment had no network access to the Gemini API and no API key, so")
        a("faithfulness / answer relevancy / context precision & recall (RAGAS), citation quality and abstention")
        a("correctness *with the LLM* were not measured. Nothing is reported in their place. Run `make eval-llm` (and")
        a('`make eval-llm ARGS="--judge --ragas"`) with `GEMINI_API_KEY` set; the quality gate will then include it.')
    a("")
    a("## 6. Limits of this evaluation")
    a("")
    a(
        "- The golden set (241 items) was authored by the engineering team (AI-assisted) and checked against the source text, **not reviewed by a lawyer**."
    )
    a("- Negative classes are small (4–14 items per class per split): decision-layer rates have wide uncertainty.")
    a("- The dense component is LSA (classical); neural embeddings and the cross-encoder could not be benchmarked offline.")
    a("- Egyptian-dialect scenario questions are the weakest category (see by-style table).")
    (R / "EVALUATION_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {R / 'EVALUATION_REPORT.md'}")


def _has(p: str) -> bool:
    try:
        metadata.version(p)
        return True
    except metadata.PackageNotFoundError:
        return False


if __name__ == "__main__":
    main()
